"""Engagement report generator.

Assembles a portable Markdown report on demand — the operator clicks "Export
report" in the Crack view; nothing is auto-downloaded, written to disk, or sent
anywhere by the tool itself. The response is handed to the browser, which turns
it into a file the operator saves.

The report has two sources:

  * the immutable audit log (every action, scope check, and rejection); and
  * the recovered credentials, which the audit DB deliberately never stores in
    plaintext, so they are pulled from the in-memory managers at export time
    (the recovered PSK from crack, a cracked WPS PIN/PSK, evil-twin creds).

That means the report reflects the CURRENT session's findings — the same values
the UI is showing — which is exactly what an operator wants to hand to a client.
"""

from datetime import datetime, timezone

from app import logging_db
from app.crack import crack_manager
from app.eviltwin import eviltwin_manager
from app.scope import current_scope
from app.wps import wps_manager


def _cell(text: object) -> str:
    """Keep a value safe inside a Markdown table cell (no stray pipes/newlines)."""
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _scope_section() -> list[str]:
    scope = current_scope.as_dict()
    rows = [f"| BSSID | `{_cell(b)}` |" for b in scope.get("bssids", [])]
    rows += [f"| SSID | `{_cell(s)}` |" for s in scope.get("ssids", [])]
    if not scope.get("is_set") or not rows:
        return ["_No engagement scope was set._"]
    return ["| Type | Value |", "|------|-------|", *rows]


def _recovered_rows() -> list[str]:
    rows: list[str] = []
    c = crack_manager.status()
    if c.psk:
        method = c.engine or "hashcat"
        if c.attack_mode:
            method += f" · {c.attack_mode}"
        rows.append(f"| `{_cell(c.bssid or '—')}` | WPA/WPA2 PSK | `{_cell(c.psk)}` | {_cell(method)} |")
    w = wps_manager.status()
    wps_method = f"{w.engine or 'reaver'} · {w.attack or 'pixie'}"
    if w.pin:
        rows.append(f"| `{_cell(w.bssid or '—')}` | WPS PIN | `{_cell(w.pin)}` | {_cell(wps_method)} |")
    if w.psk:
        rows.append(f"| `{_cell(w.bssid or '—')}` | WPA/WPA2 PSK (via WPS) | `{_cell(w.psk)}` | {_cell(wps_method)} |")
    return rows


def build_report() -> str:
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    log = logging_db.get_log()  # newest first

    out: list[str] = [
        "# WiFi Penetration Test — Engagement Report",
        "",
        f"**Generated:** {generated}  ",
        "**Tool:** WiFi Pentest Toolkit",
        "",
        "> Authorized engagement only. Every action below is recorded in the tool's immutable audit log.",
        "",
        "## 1. Engagement scope",
        "",
        *_scope_section(),
        "",
        "## 2. Recovered credentials",
        "",
    ]

    rows = _recovered_rows()
    if rows:
        out += ["| Target | Type | Credential | Method |", "|--------|------|------------|--------|", *rows]
    else:
        out.append("_No PSK/PIN was recovered in this session._")
    out.append("")

    captured = eviltwin_manager.status().captured or []
    if captured:
        out += [
            f"Evil-twin captive portal captured **{len(captured)}** credential set(s):",
            "",
            "| Time | Client | Fields |",
            "|------|--------|--------|",
        ]
        for cred in captured:
            fields = cred.get("fields", {}) if isinstance(cred, dict) else {}
            field_str = ", ".join(f"{k}={v}" for k, v in fields.items())
            out.append(
                f"| {_cell(cred.get('timestamp', '—'))} | `{_cell(cred.get('client', '—'))}` | {_cell(field_str)} |"
            )
        out.append("")

    out += ["## 3. Action timeline (audit log)", ""]
    if not log:
        out.append("_No actions were logged._")
    else:
        out += [
            "| Time (UTC) | Action | Target | Result | Detail |",
            "|------------|--------|--------|--------|--------|",
        ]
        for e in reversed(log):  # oldest-first reads like a timeline
            out.append(
                f"| {_cell(e.get('timestamp', ''))} "
                f"| {_cell(e.get('action', ''))} "
                f"| {_cell(e.get('target') or '—')} "
                f"| {_cell(e.get('result', ''))} "
                f"| {_cell(e.get('detail') or '')} |"
            )

    out += [
        "",
        "---",
        "_Generated by WiFi Pentest Toolkit. Recovered secrets are included for the authorized client's remediation only._",
        "",
    ]
    return "\n".join(out)


def report_filename() -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    return f"engagement-report-{stamp}.md"
